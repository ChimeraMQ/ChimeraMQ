func TestRuntimeTransformData(t *testing.T) {
	cfg := DefaultRuntimeConfig()
	rt := NewRuntime(cfg)
	defer rt.Close()

	if err := rt.Compile("data", testDataWasm(t)); err != nil {
		t.Fatal(err)
	}

	result, err := rt.Transform(context.Background(), "data", []byte("hello"))
	if err != nil {
		t.Fatal(err)
	}
	if result.Drop || result.Passthru {
		t.Error("expected data result, not drop or passthru")
	}
	if string(result.Data) != "hi" {
		t.Errorf("data = %q, want 'hi'", result.Data)
	}
}

