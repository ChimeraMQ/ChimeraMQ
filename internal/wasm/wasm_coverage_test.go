func TestPipelineApplyDataPayload(t *testing.T) {
	cfg := DefaultRuntimeConfig()
	rt := NewRuntime(cfg)
	defer rt.Close()

	if err := rt.Compile("data", testDataWasm(t)); err != nil {
		t.Fatal(err)
	}

	pipeline := NewPipeline([]TransformStage{{Module: "data"}}, PolicySkip)
	env := &message.Envelope{Payload: []byte("original")}

	result, err := pipeline.Apply(context.Background(), rt, env)
	if err != nil {
		t.Fatal(err)
	}
	if result == nil {
		t.Fatal("expected non-nil result")
	}
	if string(result.Payload) != "hi" {
		t.Errorf("payload = %q, want 'hi'", result.Payload)
	}
}
